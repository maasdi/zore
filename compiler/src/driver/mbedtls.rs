#[cfg(test)]
mod tests {
    use sha2::{Digest, Sha256};

    #[test]
    fn embedded_closure_matches_reviewed_digest() {
        let mut hash = Sha256::new();
        let mut previous = "";
        for &(name, contents) in super::SOURCES {
            assert!(name > previous);
            assert!(!name.contains(".."));
            previous = name;
            for bytes in [name.as_bytes(), contents] {
                hash.update((bytes.len() as u64).to_le_bytes());
                hash.update(bytes);
            }
        }
        assert_eq!(format!("{:x}", hash.finalize()), super::FINGERPRINT);
        let manifest = super::SOURCES
            .iter()
            .find(|(name, _)| *name == "SHA256SUMS")
            .unwrap()
            .1;
        let manifest = std::str::from_utf8(manifest).unwrap();
        assert_eq!(manifest.lines().count(), super::SOURCES.len() - 1);
        for line in manifest.lines() {
            let (digest, name) = line.split_once("  ").unwrap();
            let contents = super::SOURCES
                .iter()
                .find(|(path, _)| *path == name)
                .unwrap()
                .1;
            assert_eq!(format!("{:x}", Sha256::digest(contents)), digest, "{name}");
        }
    }
}
